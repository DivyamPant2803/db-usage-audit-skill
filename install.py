#!/usr/bin/env python3
"""Install the db-usage-audit skill into a project for one or more AI coding tools.

The skill itself (SKILL.md + references/ + scripts/) is plain markdown and
Python, so it is the same for every tool. This installer copies it into the
target project and writes the small "pointer" file each tool uses to discover
instructions.

  python3 install.py --target /path/to/your-repo --tool cursor
  python3 install.py --target . --tool all

Tools:
  claude    .claude/skills/db-usage-audit/            (Claude Code skill)
  cursor    .cursor/rules/db-usage-audit.mdc          (+ .db-usage-audit/)
  copilot   .github/prompts/db-usage-audit.prompt.md  (+ .db-usage-audit/)
  windsurf  .windsurf/rules/db-usage-audit.md         (+ .db-usage-audit/)
  cline     .clinerules/db-usage-audit.md             (+ .db-usage-audit/)
  agents    AGENTS.md section (Codex, Gemini CLI, Copilot agent, others)
  all       everything above

Re-running is safe: files this script generated are refreshed; files it did not
generate are left alone unless you pass --force. Python 3.8+, stdlib only.
"""
import argparse
import json
import os
import re
import shutil
import sys

SKILL_ITEMS = ["SKILL.md", "references", "scripts"]
NEUTRAL_DIR = ".db-usage-audit"
MARKER = "generated by db-usage-audit install.py"
AGENTS_START = "<!-- db-usage-audit:start -->"
AGENTS_END = "<!-- db-usage-audit:end -->"
TOOLS = ["claude", "cursor", "copilot", "windsurf", "cline", "agents"]


def read_description(skill_md):
    with open(skill_md, encoding="utf-8") as f:
        text = f.read()
    m = re.search(r"^description:\s*(.+)$", text, re.M)
    if not m:
        sys.exit("error: could not find a description in SKILL.md frontmatter")
    return m.group(1).strip()


def copy_skill(src, dest):
    os.makedirs(dest, exist_ok=True)
    for item in SKILL_ITEMS:
        s = os.path.join(src, item)
        d = os.path.join(dest, item)
        if os.path.isdir(s):
            shutil.copytree(s, d, dirs_exist_ok=True,
                            ignore=shutil.ignore_patterns("__pycache__", "*.pyc"))
        else:
            shutil.copy2(s, d)
    print(f"  copied skill -> {dest}")


def write_generated(path, content, force):
    """Write a generated adapter file, never clobbering a hand-written one."""
    if os.path.exists(path) and not force:
        with open(path, encoding="utf-8") as f:
            if MARKER not in f.read():
                print(f"  skipped {path} (exists and was not generated by this installer; use --force)")
                return
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8") as f:
        f.write(content)
    print(f"  wrote {path}")


def body(skill_path):
    return (
        f"<!-- {MARKER} -->\n"
        "# DB usage audit\n\n"
        "When the user asks to audit database usage, map which workflows (endpoints, background jobs, "
        "queue or function triggers, startup tasks) touch which tables and columns, check index coverage, "
        "or produce a DB usage report for later optimization, follow the full instructions in "
        f"`{skill_path}` exactly. Read that file first, then read the files it points to under "
        f"`{os.path.dirname(skill_path)}/references/` when a phase says to.\n\n"
        "Run in agent mode (the agent must be able to read the repo, write files and run shell commands). "
        "Output: `DB_USAGE_REPORT.md` and `DB_USAGE_REPORT.xlsx` at the repo root.\n"
    )


def install_claude(src, target, force):
    copy_skill(src, os.path.join(target, ".claude", "skills", "db-usage-audit"))


def install_cursor(desc, target, force):
    fm = f"---\ndescription: {json.dumps(desc)}\nglobs:\nalwaysApply: false\n---\n"
    write_generated(os.path.join(target, ".cursor", "rules", "db-usage-audit.mdc"),
                    fm + body(f"{NEUTRAL_DIR}/SKILL.md"), force)


def install_copilot(desc, target, force):
    fm = f"---\nagent: agent\ndescription: {json.dumps(desc)}\n---\n"
    write_generated(os.path.join(target, ".github", "prompts", "db-usage-audit.prompt.md"),
                    fm + body(f"{NEUTRAL_DIR}/SKILL.md"), force)


def install_windsurf(desc, target, force):
    fm = f"---\ntrigger: model_decision\ndescription: {json.dumps(desc)}\n---\n"
    write_generated(os.path.join(target, ".windsurf", "rules", "db-usage-audit.md"),
                    fm + body(f"{NEUTRAL_DIR}/SKILL.md"), force)


def install_cline(desc, target, force):
    write_generated(os.path.join(target, ".clinerules", "db-usage-audit.md"),
                    body(f"{NEUTRAL_DIR}/SKILL.md"), force)


def install_agents(desc, target, force):
    path = os.path.join(target, "AGENTS.md")
    section = f"{AGENTS_START}\n{body(f'{NEUTRAL_DIR}/SKILL.md')}{AGENTS_END}\n"
    existing = ""
    if os.path.exists(path):
        with open(path, encoding="utf-8") as f:
            existing = f.read()
    if AGENTS_START in existing and AGENTS_END in existing:
        pattern = re.compile(re.escape(AGENTS_START) + r".*?" + re.escape(AGENTS_END) + r"\n?", re.S)
        new = pattern.sub(lambda _: section, existing)
    else:
        new = (existing.rstrip() + "\n\n" if existing.strip() else "") + section
    with open(path, "w", encoding="utf-8") as f:
        f.write(new)
    print(f"  updated {path} (section between db-usage-audit markers)")


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--target", default=".", help="project to install into (default: current directory)")
    ap.add_argument("--tool", action="append", choices=TOOLS + ["all"],
                    help="tool to set up; repeat for several, or use 'all'")
    ap.add_argument("--force", action="store_true", help="overwrite adapter files not generated by this installer")
    args = ap.parse_args()

    tools = args.tool or []
    if not tools:
        sys.exit("error: choose at least one --tool (claude, cursor, copilot, windsurf, cline, agents, all)")
    if "all" in tools:
        tools = TOOLS

    src = os.path.dirname(os.path.abspath(__file__))
    target = os.path.abspath(args.target)
    if not os.path.isdir(target):
        sys.exit(f"error: target {target} is not a directory")
    if os.path.samefile(src, target):
        sys.exit("error: target is the skill folder itself; point --target at your project repo")
    desc = read_description(os.path.join(src, "SKILL.md"))

    print(f"Installing db-usage-audit into {target}")
    if any(t != "claude" for t in tools):
        copy_skill(src, os.path.join(target, NEUTRAL_DIR))
    dispatch = {
        "claude": lambda: install_claude(src, target, args.force),
        "cursor": lambda: install_cursor(desc, target, args.force),
        "copilot": lambda: install_copilot(desc, target, args.force),
        "windsurf": lambda: install_windsurf(desc, target, args.force),
        "cline": lambda: install_cline(desc, target, args.force),
        "agents": lambda: install_agents(desc, target, args.force),
    }
    for t in tools:
        print(f"[{t}]")
        dispatch[t]()

    print("\nDone. Suggested: add '.db-audit-work/' to your .gitignore (the audit's scratch folder).")
    print("Then open your AI tool in agent mode and ask it to run the DB usage audit (see README).")


if __name__ == "__main__":
    main()
